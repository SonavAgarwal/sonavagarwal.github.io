import { mkdir, readdir, readFile, rename, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptsDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectDirectory = path.dirname(scriptsDirectory);

export const articlesDirectory = path.join(projectDirectory, "src", "articles");

const registryPath = path.join(articlesDirectory, "articles.generated.ts");
const pageFilePattern = /^page\.(?:js|jsx|ts|tsx)$/;
const slugPattern = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const reservedKeys = new Set([
    "await",
    "break",
    "case",
    "catch",
    "class",
    "const",
    "continue",
    "debugger",
    "default",
    "delete",
    "do",
    "else",
    "enum",
    "export",
    "extends",
    "false",
    "finally",
    "for",
    "function",
    "if",
    "implements",
    "import",
    "in",
    "instanceof",
    "interface",
    "let",
    "new",
    "null",
    "package",
    "private",
    "protected",
    "public",
    "return",
    "static",
    "super",
    "switch",
    "this",
    "throw",
    "true",
    "try",
    "typeof",
    "var",
    "void",
    "while",
    "with",
    "yield",
]);

function slugToKey(slug) {
    return slug.replace(/-([a-z0-9])/g, (_, character) =>
        character.toUpperCase(),
    );
}

async function findArticles() {
    await mkdir(articlesDirectory, { recursive: true });

    const entries = await readdir(articlesDirectory, { withFileTypes: true });
    const articles = [];

    for (const entry of entries) {
        if (!entry.isDirectory()) continue;

        const files = await readdir(path.join(articlesDirectory, entry.name));
        const pageFiles = files.filter((file) => pageFilePattern.test(file));

        if (pageFiles.length === 0) continue;
        if (pageFiles.length > 1) {
            throw new Error(
                `Article "${entry.name}" has multiple page files: ${pageFiles.join(", ")}`,
            );
        }
        if (!slugPattern.test(entry.name)) {
            throw new Error(
                `Article folder "${entry.name}" must be lowercase kebab-case (for example, "my-article").`,
            );
        }

        const key = slugToKey(entry.name);
        if (reservedKeys.has(key)) {
            throw new Error(
                `Article folder "${entry.name}" generates the reserved JavaScript key "${key}". Rename the folder.`,
            );
        }

        articles.push({
            key,
            pageFile: pageFiles[0],
            slug: entry.name,
        });
    }

    articles.sort((left, right) => left.slug.localeCompare(right.slug));

    const keys = new Set();
    for (const article of articles) {
        if (keys.has(article.key)) {
            throw new Error(
                `Multiple article folders generate the key "${article.key}". Rename one of them.`,
            );
        }
        keys.add(article.key);
    }

    return articles;
}

function renderRegistry(articles) {
    const imports = articles.map(
        ({ key, pageFile, slug }) =>
            `import * as ${key} from "./${slug}/${pageFile.replace(/\.[^.]+$/, "")}";`,
    );
    const members = articles.map(({ key }) => `    ${key},`);
    const keysBySlug = articles.map(({ key, slug }) => {
        const property = slug.includes("-") ? JSON.stringify(slug) : slug;
        return `    ${property}: "${key}",`;
    });

    return [
        "// This file is generated by scripts/generate-articles.mjs.",
        "// Do not edit it directly.",
        "",
        ...imports,
        ...(imports.length > 0 ? [""] : []),
        "export const ARTICLES = {",
        ...members,
        "} as const;",
        "",
        "export type ArticleKey = keyof typeof ARTICLES;",
        "",
        "export const ARTICLE_KEYS_BY_SLUG = {",
        ...keysBySlug,
        "} as const satisfies Record<string, ArticleKey>;",
        "",
        "export type ArticleSlug = keyof typeof ARTICLE_KEYS_BY_SLUG;",
        "",
    ].join("\n");
}

export async function generateArticlesRegistry() {
    const articles = await findArticles();
    const nextContents = renderRegistry(articles);
    const currentContents = await readFile(registryPath, "utf8").catch(
        () => undefined,
    );

    if (currentContents === nextContents) return false;

    const temporaryPath = `${registryPath}.${process.pid}.tmp`;
    await writeFile(temporaryPath, nextContents, "utf8");
    await rename(temporaryPath, registryPath);

    console.log(
        `Generated ${path.relative(projectDirectory, registryPath)} with ${articles.length} article${articles.length === 1 ? "" : "s"}.`,
    );
    return true;
}

const isDirectRun =
    process.argv[1] &&
    path.resolve(process.argv[1]) ===
        path.resolve(fileURLToPath(import.meta.url));

if (isDirectRun) {
    generateArticlesRegistry().catch((error) => {
        console.error(error);
        process.exitCode = 1;
    });
}
